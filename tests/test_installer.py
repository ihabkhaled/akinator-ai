@needs_ps
def test_ps_user_install_gives_one_skill_everywhere(world: dict) -> None:
    result = run_ps(world)
    assert result.returncode == 0, result.stdout + result.stderr
    _assert_user_install(world)
    assert "plugin install akinator@akinator --scope user" in world["log"].read_text("utf-8")


@needs_ps
def test_ps_repo_install_leaves_the_host_clean_and_uninstall_restores_it(
    world: dict, tmp_path: Path
) -> None:
    repo = _host_repo(tmp_path / "host")
    before = _snapshot(repo)
    result = run_ps(world, "-Repo", str(repo), "-Codex", "-Cursor")
    assert result.returncode == 0, result.stdout + result.stderr
    _assert_repo_install(repo)
    result = run_ps(world, "-Repo", str(repo), "-Codex", "-Cursor", "-Uninstall")
    assert result.returncode == 0, result.stdout + result.stderr
    assert _snapshot(repo) == before, "uninstall did not restore the host exactly"


@needs_ps
@needs_sh
def test_both_installers_write_the_same_block(world: dict, tmp_path: Path) -> None:
    """Two installers for one contract: they must not drift apart."""
    a = _host_repo(tmp_path / "a")
    b = _host_repo(tmp_path / "b")
    assert run_sh(world, "--repo", _posix(a), "--codex").returncode == 0
    assert run_ps(world, "-Repo", str(b), "-Codex").returncode == 0
    assert (a / "AGENTS.md").read_bytes() == (b / "AGENTS.md").read_bytes()
