@needs_sh
def test_sh_user_install_gives_one_skill_everywhere(world: dict) -> None:
    result = run_sh(world)
    assert result.returncode == 0, result.stdout + result.stderr
    _assert_user_install(world)
    calls = world["log"].read_text("utf-8")
    assert "plugin marketplace add" in calls and "--scope user" in calls
    assert "plugin install akinator@akinator --scope user" in calls


@needs_sh
def test_sh_reinstall_is_idempotent(world: dict) -> None:
    assert run_sh(world).returncode == 0
    first = _snapshot(world["home"])
    assert run_sh(world).returncode == 0
    assert _snapshot(world["home"]) == first, "a reinstall changed the result"


@needs_sh
def test_sh_repo_install_leaves_the_host_clean_and_uninstall_restores_it(
    world: dict, tmp_path: Path
) -> None:
    repo = _host_repo(tmp_path / "host")
    before = _snapshot(repo)
    result = run_sh(world, "--repo", _posix(repo), "--codex", "--cursor")
    assert result.returncode == 0, result.stdout + result.stderr
    _assert_repo_install(repo)

    result = run_sh(world, "--repo", _posix(repo), "--codex", "--cursor", "--uninstall")
    assert result.returncode == 0, result.stdout + result.stderr
    assert _snapshot(repo) == before, "uninstall did not restore the host exactly"
    assert not (repo / ".agents").exists() and not (repo / ".cursor").exists(), (
        "uninstall left the empty directories it created")


@needs_sh
def test_sh_never_removes_what_it_does_not_own(world: dict) -> None:
    assert run_sh(world).returncode == 0
    assert run_sh(world, "--codex", "--cursor", "--uninstall").returncode == 0
    home = world["home"]
    assert (home / ".agents" / "skills" / "akinator-notes" / "SKILL.md").read_text("utf-8") == THEIRS
    assert not (home / ".agents" / "skills" / "akinator").exists()
    assert (home / ".codex" / "AGENTS.md").read_text("utf-8") == "# My Codex notes\n\nKeep me.\n"


@needs_sh
def test_sh_help_works_when_piped_like_curl(world: dict) -> None:
    """`curl ... | sh` has no script file to read help text from."""
    script = (REPO / "install.sh").read_text(encoding="utf-8")
    result = run_sh(world, "--help", stdin=script)
    assert result.returncode == 0
    assert "/akinator:everything" in result.stdout and "--repo" in result.stdout


@needs_sh
def test_sh_rejects_an_unknown_option(world: dict) -> None:
    result = run_sh(world, "--everything")
    assert result.returncode != 0
    assert "unknown option" in result.stderr


@needs_sh
def test_sh_warns_when_an_override_file_hides_the_block(world: dict) -> None:
    """Codex reads AGENTS.override.md INSTEAD of AGENTS.md when it is non-empty,
    so a block written only to AGENTS.md would silently do nothing."""
    (world["home"] / ".codex" / "AGENTS.override.md").write_text("override\n", encoding="utf-8")
    result = run_sh(world, "--codex")
    assert result.returncode == 0
    assert "AGENTS.override.md" in result.stderr


